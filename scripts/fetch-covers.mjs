/**
 * Fetch Open Library covers for every catalog title.
 * Writes public/covers/*.jpg and src/covers-data.js
 */
import { writeFile, mkdir } from 'node:fs/promises'
import { createWriteStream } from 'node:fs'
import { pipeline } from 'node:stream/promises'
import { Readable } from 'node:stream'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

// Inline catalog titles (avoid importing browser modules)
const { shelves } = await import(path.join(root, 'src/catalog.js'))

const outDir = path.join(root, 'public/covers')
await mkdir(outDir, { recursive: true })

const results = {}
const gaps = []

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms))
}

function slug(shelfId, index) {
  return `${shelfId}-${index}`
}

async function searchOpenLibrary(title, author) {
  const q = new URLSearchParams({
    title: title.replace(/\s*\(.*?\)\s*/g, ' ').slice(0, 120),
    limit: '8',
  })
  if (author && !/uncertain|various|anthology|associated/i.test(author)) {
    const a = author
      .replace(/^edited by\s+/i, '')
      .replace(/^tr\.?\s+/i, '')
      .split(/[;(]/)[0]
      .trim()
      .slice(0, 60)
    if (a) q.set('author', a)
  }
  const url = `https://openlibrary.org/search.json?${q}`
  const res = await fetch(url, { headers: { Accept: 'application/json' } })
  if (!res.ok) throw new Error(`search ${res.status}`)
  return res.json()
}

async function downloadCover(coverId, dest) {
  const url = `https://covers.openlibrary.org/b/id/${coverId}-L.jpg`
  const res = await fetch(url)
  if (!res.ok || !res.body) return false
  const ctype = res.headers.get('content-type') || ''
  if (!ctype.includes('image')) return false
  await pipeline(Readable.fromWeb(res.body), createWriteStream(dest))
  return true
}

async function processBook(shelfId, book, index) {
  const id = slug(shelfId, index)
  const dest = path.join(outDir, `${id}.jpg`)
  try {
    const data = await searchOpenLibrary(book.title, book.author)
    const docs = data.docs || []
    // Prefer docs with cover_i
    const withCover = docs.filter((d) => d.cover_i)
    const pick = withCover[0] || docs[0]
    if (!pick?.cover_i) {
      gaps.push({ id, title: book.title, author: book.author, reason: 'no cover_i in Open Library' })
      results[id] = { cover: null, source: null, match: null, gap: true }
      return
    }
    const ok = await downloadCover(pick.cover_i, dest)
    if (!ok) {
      gaps.push({ id, title: book.title, author: book.author, reason: 'cover download failed' })
      results[id] = { cover: null, source: null, match: null, gap: true }
      return
    }
    const matchTitle = pick.title || ''
    const matchAuthor = (pick.author_name && pick.author_name[0]) || ''
    const exactish =
      matchTitle.toLowerCase().includes(book.title.slice(0, 18).toLowerCase()) ||
      book.title.toLowerCase().includes(matchTitle.slice(0, 18).toLowerCase())
    results[id] = {
      cover: `covers/${id}.jpg`,
      spine: `covers/${id}.jpg`, // OL provides front covers; used as real edition imagery on spine strip
      source: 'Open Library',
      sourceUrl: pick.key ? `https://openlibrary.org${pick.key}` : `https://openlibrary.org`,
      coverId: pick.cover_i,
      match: { title: matchTitle, author: matchAuthor },
      gap: !exactish,
      note: exactish ? null : `Closest Open Library match: “${matchTitle}”${matchAuthor ? ` — ${matchAuthor}` : ''}`,
    }
    if (!exactish) {
      gaps.push({
        id,
        title: book.title,
        author: book.author,
        reason: `closest match: ${matchTitle}`,
      })
    }
    console.log('ok', id, matchTitle)
  } catch (err) {
    gaps.push({ id, title: book.title, author: book.author, reason: String(err.message || err) })
    results[id] = { cover: null, source: null, match: null, gap: true, note: String(err.message || err) }
    console.log('fail', id, err.message)
  }
}

for (const shelf of shelves) {
  for (let i = 0; i < shelf.books.length; i++) {
    await processBook(shelf.id, shelf.books[i], i)
    await sleep(120) // be polite to OL
  }
}

const js = `/** Auto-generated by scripts/fetch-covers.mjs — Open Library covers */
export const covers = ${JSON.stringify(results, null, 2)};

export const coverGaps = ${JSON.stringify(gaps, null, 2)};

export function coverFor(shelfId, index) {
  return covers[\`\${shelfId}-\${index}\`] || null;
}
`

await writeFile(path.join(root, 'src/covers-data.js'), js)
await writeFile(
  path.join(root, 'public/covers/CREDITS.md'),
  `# Cover credits

Book cover images fetched from [Open Library](https://openlibrary.org) / Internet Archive cover service for educational display in the Library bookshelf project.

Gaps / closest-match notes are recorded in \`src/covers-data.js\` (\`coverGaps\`).

Total books: ${Object.keys(results).length}
With image: ${Object.values(results).filter((r) => r.cover).length}
Gaps or approximate matches: ${gaps.length}
`,
)

console.log('Done.', Object.keys(results).length, 'books;', gaps.length, 'gaps/notes')
